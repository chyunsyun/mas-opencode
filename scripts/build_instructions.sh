#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MAS_ROOT="$(dirname "$SCRIPT_DIR")"
MAS_ROOT="${MAS_ROOT:-$MAS_ROOT}"
source "${MAS_ROOT}/lib/cli_adapter.sh"

PARTS_DIR="${MAS_ROOT}/instructions"
AGENTS_DIR="${MAS_ROOT}/.opencode/agents"
PERMISSIONS_FILE="${MAS_ROOT}/config/opencode-permissions.yaml"

PYTHON=$(_mas_python) || {
    echo "ERROR: Python with PyYAML is required." >&2
    exit 1
}

mkdir -p "$AGENTS_DIR"

normalize_markdown() {
    local path="$1"
    local tmp="${path}.tmp.$$"
    awk '{ sub(/\r$/, ""); sub(/[ \t]+$/, ""); print }' "$path" > "$tmp"
    mv "$tmp" "$path"
}

permission_for() {
    local agent_id="$1"
    "$PYTHON" - "$PERMISSIONS_FILE" "$agent_id" "$(agent_registry_role "$agent_id")" <<'PY'
import sys
import yaml

path, agent_id, role = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path, encoding="utf-8") as fh:
    config = yaml.safe_load(fh) or {}

def expand(pattern):
    return str(pattern).replace("{agent_id}", agent_id)

def rule(deny, allow):
    out = {}
    for pattern in deny or []:
        out[expand(pattern)] = "deny"
    for pattern in allow or []:
        out[expand(pattern)] = "allow"
    return out

common = config.get("common") or {}
role_cfg = (config.get("roles") or {}).get(role) or {}
permission = {
    "*": "allow",
    "question": role_cfg.get("question", "deny"),
    "read": rule(role_cfg.get("read_deny"), role_cfg.get("read_allow")),
    "edit": rule(common.get("edit_deny"), role_cfg.get("edit_allow")),
    "write": rule(common.get("edit_deny"), role_cfg.get("edit_allow")),
    "patch": rule(common.get("edit_deny"), role_cfg.get("edit_allow")),
    "list": rule(role_cfg.get("read_deny"), role_cfg.get("read_allow")),
    "glob": rule(role_cfg.get("read_deny"), role_cfg.get("read_allow")),
}
print(yaml.safe_dump({"permission": permission}, allow_unicode=True, sort_keys=False).rstrip())
PY
}

routing_for() {
    local agent_id="$1"
    "$PYTHON" - "$MAS_ROOT/config/settings.yaml" "$agent_id" <<'PY'
import sys
import yaml

path, agent = sys.argv[1], sys.argv[2]
try:
    with open(path, encoding="utf-8") as fh:
        data = yaml.safe_load(fh) or {}
except Exception:
    data = {}
cfg = ((data.get("cli") or {}).get("agents") or {}).get(agent) or {}
if not isinstance(cfg, dict):
    cfg = {}
out = {}
model = cfg.get("model")
variant = cfg.get("variant")
if model:
    out["model"] = str(model)
if variant:
    out["variant"] = str(variant)
print(yaml.safe_dump(out, allow_unicode=True, sort_keys=False).rstrip() if out else "")
PY
}

role_title() {
    case "$1" in
        director) echo "部長 — 人間の窓口、コマンド作成、最終判断" ;;
        chief) echo "係長 — 分解、割当、進捗管理、品質確認の取り回し" ;;
        engineer1) echo "エンジニア1 — 実装、テスト、報告" ;;
        engineer2) echo "エンジニア2 — 実装、テスト、報告" ;;
        engineer3) echo "エンジニア3 — 軽量高速タスク（max_bloom 3）" ;;
        auditor) echo "監査役 — 独立した品質確認、原因分析、証拠に基づく判定" ;;
    esac
}

stale=$(find "$AGENTS_DIR" -maxdepth 1 -type f -name '*.md' -printf '%f\n' 2>/dev/null || true)
for file in $stale; do
    case "$file" in
        director.md|chief.md|engineer1.md|engineer2.md|engineer3.md|auditor.md) ;;
        *) rm -f "$AGENTS_DIR/$file" ;;
    esac
done

while IFS= read -r agent_id; do
    role=$(agent_registry_role "$agent_id")
    output="${AGENTS_DIR}/${agent_id}.md"
    permission_yaml=$(permission_for "$agent_id")
    routing_yaml=$(routing_for "$agent_id")

    {
        echo "---"
        printf 'description: "%s"\n' "$(role_title "$agent_id")"
        echo "mode: primary"
        echo "# Auto-generated by scripts/build_instructions.sh. Do not edit."
        [[ -n "$routing_yaml" ]] && printf '%s\n' "$routing_yaml"
        printf '%s\n' "$permission_yaml"
        echo "---"
        echo
        cat "${PARTS_DIR}/roles/${role}_role.md"
        if [[ "$agent_id" == "engineer3" ]]; then
            echo
            cat "${PARTS_DIR}/roles/engineer_fast_role.md"
        fi
        echo
        echo "## Identity Anchor"
        echo
        echo "- agent_id: \`${agent_id}\`"
        echo "- 表示名: \`$(agent_registry_label "$agent_id")\`"
        echo "- tmux確認: \`tmux display-message -t \"\$TMUX_PANE\" -p '#{@agent_id}'\`"
        echo "- 上記が \`${agent_id}\` と一致しない場合は作業を開始しない。"
        echo
        cat "${PARTS_DIR}/common/protocol.md"
        echo
        cat "${PARTS_DIR}/common/task_flow.md"
        echo
        cat "${PARTS_DIR}/common/forbidden_actions.md"
        echo
        cat "${PARTS_DIR}/opencode_tools.md"
    } > "$output"
    normalize_markdown "$output"
    echo "generated: .opencode/agents/${agent_id}.md"
done < <(agent_registry_agents)

cp "${PARTS_DIR}/AGENTS.md" "${MAS_ROOT}/AGENTS.md"
normalize_markdown "${MAS_ROOT}/AGENTS.md"
echo "generated: AGENTS.md"
